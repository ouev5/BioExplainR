# Chinese table: read lazily from a UTF-8 data file so R sources stay ASCII.
.app_msgs_zh <- function() {
  cached <- .pkg_env$app_msgs_zh
  if (!is.null(cached)) return(cached)
  path <- system.file("i18n", "app-zh.txt", package = "BioExplainR")
  out <- list()
  if (nzchar(path) && file.exists(path)) {
    lines <- readLines(path, encoding = "UTF-8", warn = FALSE)
    lines <- lines[nzchar(trimws(lines)) & !startsWith(trimws(lines), "#")]
    pos <- regexpr(" = ", lines, fixed = TRUE)
    ok <- pos > 0
    keys <- trimws(substr(lines[ok], 1L, pos[ok] - 1L))
    vals <- substring(lines[ok], pos[ok] + 3L)
    Encoding(vals) <- "UTF-8"
    out <- stats::setNames(as.list(vals), keys)
  }
  .pkg_env$app_msgs_zh <- out
  out
}

# Look up a string; extra arguments go to sprintf(). Missing Chinese entries fall back to English.
.app_t <- function(key, language = .default_language, ...) {
  language <- .check_language(language)
  en <- .app_msgs[[key]]
  if (is.null(en)) stop("Unknown interface string: ", key, call. = FALSE)
  txt <- en
  if (identical(language, "zh")) {
    zh <- .app_msgs_zh()[[key]]
    if (!is.null(zh)) txt <- zh
  }
  if (...length()) sprintf(txt, ...) else txt
}

