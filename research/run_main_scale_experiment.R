score_one <- function(expected, value) {
  available <- !is.null(value) && length(value) == 1L
  correct <- available && if (is.numeric(expected)) {
    got <- suppressWarnings(as.numeric(value))
    is.finite(got) && abs(got - expected) <= if (expected == 0) 1e-6 else abs(expected) * 1e-6
  } else identical(as.character(value), as.character(expected))
  list(answered = available, correct = isTRUE(correct))
}
claims_as_list <- function(parsed) {
  claims <- parsed$claims %||% list()
  if (is.data.frame(claims)) claims <- lapply(seq_len(nrow(claims)), function(i) as.list(claims[i, ]))
  if (is.list(claims)) claims else list()
}

run_one <- function(i) {
  task <- tasks[i, ]; c <- cases[[as.character(task$case)]]
  prefix <- file.path(model_dir, paste(task$case, task$method, task$replicate, sep = "__"))
  result_file <- paste0(prefix, ".json")
  if (file.exists(result_file)) {
    return(jsonlite::read_json(result_file, simplifyVector = FALSE))
  }
  payload <- bio_context_payload(c$context, max_top = 10, max_chars = 20000)
  if (task$method == "direct_bounded") {
    system <- paste("You interpret bioinformatics R output. Compute requested values only if the provided data are complete.", common)
    user <- paste("Study metadata and thresholds:", json_precise(c$context$metadata),
                  json_precise(c$context$provenance$thresholds), "R output:", json_precise(c$raw),
                  "Requested fact paths:", paste(names(c$expected), collapse = ", "))
  } else {
    system <- paste(BioExplainR:::.llm_system_prompt("zh", "beginner"), common)
    ev <- if (task$method == "facts_evidence") evidence else NULL
    user <- paste(BioExplainR:::.llm_user_prompt(payload, ev),
                  "Facts:", json_precise(c$expected),
                  "Requested fact paths:", paste(names(c$expected), collapse = ", "))
  }
  write_json_safe(list(system = system, user = user), paste0(prefix, "__prompt.json"))
  response <- tryCatch(bio_llm_chat(cfg, system, user), error = function(e) list(error = bio_redact(conditionMessage(e))))
  parsed <- if (is.null(response$error)) BioExplainR:::.parse_model_json(response$text) else NULL
  claims <- claims_as_list(parsed %||% list())
  scores <- lapply(names(c$expected), function(path) {
    hits <- Filter(function(cl) is.list(cl) && identical(as.character(cl$fact %||% ""), path), claims)
    value <- if (length(hits) == 1L) hits[[1L]]$value else NULL
    s <- score_one(c$expected[[path]], value)
    list(fact = path, expected = c$expected[[path]], value = value,
         answered = s$answered, correct = s$correct)
  })
  ex <- bio_explain(c$context, use_llm = FALSE, evidence = if (task$method == "facts_evidence") evidence else NULL)
  ex$llm <- parsed
  checked <- if (!is.null(parsed)) bio_validate_explanation(ex) else list(validation = list(status = "unverified"))
  output <- list(case = task$case, family = c$family, method = task$method, replicate = task$replicate,
                 requested_model = cfg$model, requested_thinking = "disabled", requested_temperature = 0,
                 created_utc = format(Sys.time(), tz = "UTC", usetz = TRUE), response = response,
                 parsed = parsed, validation = checked$validation, scores = scores,
                 prompt_chars = nchar(system) + nchar(user))
  write_json_safe(output, result_file)
  output
}

