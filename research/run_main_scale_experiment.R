plain <- function(x) if (is.list(x) && !is.data.frame(x)) lapply(x, plain) else x
write_json_safe <- function(x, file) {
  jsonlite::write_json(plain(x), file, pretty = TRUE, auto_unbox = TRUE,
                       null = "null", digits = 17)
}
json_precise <- function(x, pretty = TRUE) {
  jsonlite::toJSON(x, auto_unbox = TRUE, null = "null", na = "null",
                   digits = 17, pretty = pretty, force = TRUE)
}

cases <- list()
add_case <- function(name, family, input, expected, args = list(), raw = NULL, seed = NA_integer_) {
  context <- do.call(bio_context, c(list(input), args))
  # The target facts are copied from the context generated by the package, not
  # hand-entered. This keeps the scale experiment an adapter/transport test.
  stopifnot(length(expected) == 4L, all(vapply(expected, function(x) length(x) == 1L, logical(1))))
  cases[[name]] <<- list(name = name, family = family, input = input,
                         context = context, expected = expected, raw = raw,
                         seed = seed)
}

# Thirty differential-expression cases with four scalar targets each.
for (i in seq_len(30L)) {
  n <- 40L + i
  de <- data.frame(
    log2FoldChange = rep(c(2 + i / 100, -1.5 - i / 200, 0.2), length.out = n),
    padj = rep(c(0.001 + i / 100000, 0.02 + i / 100000, 0.8), length.out = n),
    row.names = paste0("gene", seq_len(n))
  )
  ctx <- bio_context(de, thresholds = list(padj = 0.05, lfc = 1))
  add_case(sprintf("de_%03d", i), "differential_expression", de,
           list(n_features = ctx$facts$n_features, n_significant = ctx$facts$n_significant,
                n_up = ctx$facts$n_up, n_down = ctx$facts$n_down),
           list(thresholds = list(padj = 0.05, lfc = 1)),
           raw = list(dim = dim(de), provided_rows = utils::head(de, 10), rows_complete = FALSE))
}

# Twenty ORA-shaped result cases.
for (i in seq_len(20L)) {
  n <- 12L + i
  tab <- data.frame(
    ID = paste0("TERM", seq_len(n)), Description = paste("Term", seq_len(n)),
    GeneRatio = paste0((seq_len(n) %% 7L) + 1L, "/20"),
    Count = (seq_len(n) %% 7L) + 1L,
    p.adjust = ((seq_len(n) %% (5L + i %% 4L)) + 1L) / 100
  )
  ctx <- bio_context(tab, analysis_type = "enrichment_ora", thresholds = list(padj = 0.05))
  add_case(sprintf("enrichment_%03d", i), "enrichment", tab,
           list(n_terms = ctx$facts$n_terms, n_significant = ctx$facts$n_significant,
                enrichment_method = ctx$facts$enrichment_method,
                significance_threshold = ctx$facts$significance_threshold),
           list(analysis_type = "enrichment_ora", thresholds = list(padj = 0.05)),
           raw = list(dim = dim(tab), provided_rows = utils::head(tab, 10), rows_complete = FALSE))
}

# Twenty PCA cases. Numeric targets remain full precision in the prompt and
# are requested as exact scalar claims.
for (i in seq_len(20L)) {
  seed <- 1000L + i
  set.seed(seed)
  x <- matrix(rnorm((8L + i %% 5L) * (12L + i)), nrow = 8L + i %% 5L)
  fit <- prcomp(x, center = TRUE, scale. = FALSE)
  ctx <- bio_context(fit)
  add_case(sprintf("pca_%03d", i), "pca", fit,
           list(n_observations = ctx$facts$n_observations, n_variables = ctx$facts$n_variables,
                "variance_explained.1" = ctx$facts$variance_explained[1],
                "variance_explained.2" = ctx$facts$variance_explained[2]),
           raw = list(sdev = fit$sdev, observations = nrow(fit$x), variables = nrow(fit$rotation)),
           seed = seed)
}

# Twenty SingleCellExperiment cases.
for (i in seq_len(20L)) {
  n_features <- 25L + i
  n_cells <- 30L + i * 2L
  counts <- matrix((seq_len(n_features * n_cells) + i) %% 11L,
                   nrow = n_features, ncol = n_cells,
                   dimnames = list(paste0("g", seq_len(n_features)), paste0("c", seq_len(n_cells))))
  sample_ids <- rep(paste0("s", seq_len(1L + i %% 3L)), length.out = n_cells)
  sce <- SingleCellExperiment(assays = list(counts = counts),
                              colData = DataFrame(sample_id = sample_ids))
  ctx <- bio_context(sce, sample_col = "sample_id")
  add_case(sprintf("single_cell_%03d", i), "single_cell", sce,
           list(n_cells = ctx$facts$n_cells, n_features = ctx$facts$n_features,
                n_samples = ctx$facts$n_samples, assays = ctx$facts$assays[1]),
           list(sample_col = "sample_id"),
           raw = list(dim = dim(counts), assays = "counts", n_distinct_samples = length(unique(sample_ids))))
}

# Fifteen cell-composition cases with coherent sample-level group labels.
for (i in seq_len(15L)) {
  n_samples <- 4L + i %% 4L
  cells_per_sample <- 18L + i
  n_cells <- n_samples * cells_per_sample
  md <- data.frame(
    sample = rep(paste0("sample", seq_len(n_samples)), each = cells_per_sample),
    cluster = rep(paste0("cluster", seq_len(2L + i %% 3L)), length.out = n_cells),
    group = rep(rep(c("control", "treated"), length.out = n_samples), each = cells_per_sample),
    stringsAsFactors = FALSE
  )
  cp <- bio_cell_proportions(md, sample_col = "sample", cluster_col = "cluster", group_col = "group")
  ctx <- bio_context(cp)
  add_case(sprintf("cell_composition_%03d", i), "cell_composition", cp,
           list(n_cells_used = ctx$facts$n_cells_used, n_samples = ctx$facts$n_samples,
                n_clusters = ctx$facts$n_clusters, n_groups = ctx$facts$n_groups),
           raw = list(n_cells = n_cells, n_samples = n_samples, n_clusters = length(unique(md$cluster))))
}

